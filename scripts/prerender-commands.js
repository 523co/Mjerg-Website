/* Writes the full command list into commands.html, so search engines and
   link previews see it without running JavaScript. js/commands.js still
   takes over in the browser for search and filtering.

   Run after editing js/commands.js:   node scripts/prerender-commands.js */

"use strict";

var fs = require("fs");
var path = require("path");
var vm = require("vm");

var root = path.join(__dirname, "..");
var page = path.join(root, "commands.html");

// just enough of a DOM for js/commands.js to render into
function el() {
  return { innerHTML: "", textContent: "", addEventListener: function () {},
           querySelectorAll: function () { return []; } };
}
var els = { "cmd-list": el(), "cmd-search": el(), "cmd-chips": el(), "cmd-count": el() };
var sandbox = { window: {}, document: { getElementById: function (id) { return els[id] || null; } } };

vm.runInNewContext(fs.readFileSync(path.join(root, "js/commands.js"), "utf8"), sandbox);

var list = els["cmd-list"].innerHTML
  .replace(/<section /g, "\n    <section ")
  .replace(/<div class="cmd">/g, "\n      <div class=\"cmd\">");

var html = fs.readFileSync(page, "utf8");
var start = "<!-- commands:start -->", end = "<!-- commands:end -->";
var a = html.indexOf(start), b = html.indexOf(end);
if (a === -1 || b === -1) throw new Error("commands.html is missing the " + start + " / " + end + " markers");

html = html.slice(0, a + start.length) +
  "\n    <!-- generated by scripts/prerender-commands.js, don't edit by hand -->" + list + "\n    " +
  html.slice(b);
html = html.replace(/(<span class="small muted" id="cmd-count">)[^<]*/, "$1" + els["cmd-count"].textContent);

fs.writeFileSync(page, html);
console.log("commands.html: " + els["cmd-count"].textContent + " written");
